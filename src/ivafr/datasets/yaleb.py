"""Extended Yale Face Database B adapter.

The adapter expects the user to download Yale B into ``data/raw/yaleb``.
Raw faces are never copied into the repository or redistributed by ivafr.
"""

from __future__ import annotations

import re

import cv2
import numpy as np

from ivafr.datasets.base import Cloud3D, DatasetAdapter, Sample
from ivafr.registry import register_dataset

_SUBJECT = re.compile(r"(?:yaleB|subject)(\d+)", re.IGNORECASE)
_LIGHT = re.compile(r"_P(?P<pose>\d{2})A(?P<az>[+-]\d{3})E(?P<el>[+-]\d{2})", re.IGNORECASE)


@register_dataset("yaleb")
class YaleBAdapter(DatasetAdapter):
    """Discover Yale B images from common extracted-directory layouts."""

    name = "yaleb"

    def discover(self) -> list[Sample]:
        root = self.raw_root / self.name
        if not root.is_dir():
            raise FileNotFoundError(f"Yale B data missing at {root}; download/extract it there")
        paths = sorted(
            [
                *root.rglob("*.pgm"),
                *root.rglob("*.png"),
                *root.rglob("*.jpg"),
                *root.rglob("*.jpeg"),
                *root.rglob("*.bmp"),
            ]
        )
        samples: list[Sample] = []
        for path in paths:
            if "ambient" in path.stem.lower():
                # The v2 benchmark uses the 64 single-light frontal captures;
                # the cropped archive also contains one extra ambient image.
                continue
            match = _SUBJECT.search(path.name) or _SUBJECT.search(path.parent.name)
            if not match:
                continue
            subject = f"S{int(match.group(1)):03d}"
            token = path.stem.split("_", 1)[-1]
            light = _LIGHT.search(path.stem)
            if light:
                pose = int(light.group("pose"))
                azimuth = int(light.group("az"))
                elevation = int(light.group("el"))
                illumination = (
                    "normal"
                    if azimuth == 0 and elevation == 0
                    else f"yale:A{azimuth:+04d}E{elevation:+03d}"
                )
                notes = f"native_light={token};azimuth={azimuth};elevation={elevation}"
            else:
                pose = 0
                azimuth = 0
                elevation = 0
                illumination = f"yale:{token}"
                notes = "native_light=" + token
            sid = f"{subject}_{path.stem}"
            img = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
            if img is None:
                continue
            samples.append(
                Sample(
                    dataset=self.name,
                    subject_id=subject,
                    sample_id=sid,
                    path_2d=path,
                    meta={
                        "session": "s1",
                        "expression": "neutral",
                        "pose_yaw": 0.0 if pose == 0 else float(pose),
                        "pose_pitch": 0.0,
                        "illumination": illumination,
                        "occlusion": "none",
                        "orig_w": int(img.shape[1]),
                        "orig_h": int(img.shape[0]),
                        "n_points": 468,
                        "notes": notes,
                    },
                )
            )
        if not samples:
            raise FileNotFoundError(f"No Yale B image files found under {root}")
        return samples

    def load_2d(self, s: Sample) -> np.ndarray:
        img = cv2.imread(str(s.path_2d), cv2.IMREAD_COLOR)
        if img is None:
            raise OSError(f"Cannot read image {s.path_2d}")
        return img

    def load_3d(self, s: Sample) -> Cloud3D:
        raise RuntimeError("Yale B pseudo-3D is generated by MediaPipe FaceMesh during preprocessing")
