"""Extended Yale Face Database B adapter.

The adapter expects the user to download Yale B into ``data/raw/yaleb``.
Raw faces are never copied into the repository or redistributed by ivafr.
"""

from __future__ import annotations

import re
from pathlib import Path

import cv2
import numpy as np

from ivafr.datasets.base import Cloud3D, DatasetAdapter, Sample
from ivafr.registry import register_dataset

_SUBJECT = re.compile(r"(?:yaleB|subject)(\d+)", re.IGNORECASE)


@register_dataset("yaleb")
class YaleBAdapter(DatasetAdapter):
    """Discover Yale B images from common extracted-directory layouts."""

    name = "yaleb"

    def discover(self) -> list[Sample]:
        root = self.raw_root / self.name
        if not root.is_dir():
            raise FileNotFoundError(f"Yale B data missing at {root}; download/extract it there")
        paths = sorted(
            [
                *root.rglob("*.pgm"),
                *root.rglob("*.png"),
                *root.rglob("*.jpg"),
                *root.rglob("*.jpeg"),
                *root.rglob("*.bmp"),
            ]
        )
        samples: list[Sample] = []
        for path in paths:
            match = _SUBJECT.search(path.name) or _SUBJECT.search(path.parent.name)
            if not match:
                continue
            subject = f"S{int(match.group(1)):03d}"
            token = path.stem.split("_", 1)[-1]
            sid = f"{subject}_{path.stem}"
            img = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
            if img is None:
                continue
            samples.append(
                Sample(
                    dataset=self.name,
                    subject_id=subject,
                    sample_id=sid,
                    path_2d=path,
                    meta={
                        "session": "s1",
                        "expression": "neutral",
                        "pose_yaw": 0.0,
                        "pose_pitch": 0.0,
                        "illumination": f"yale:{token}",
                        "occlusion": "none",
                        "orig_w": int(img.shape[1]),
                        "orig_h": int(img.shape[0]),
                        "n_points": 468,
                    },
                )
            )
        if not samples:
            raise FileNotFoundError(f"No Yale B image files found under {root}")
        return samples

    def load_2d(self, s: Sample) -> np.ndarray:
        img = cv2.imread(str(s.path_2d), cv2.IMREAD_COLOR)
        if img is None:
            raise IOError(f"Cannot read image {s.path_2d}")
        return img

    def load_3d(self, s: Sample) -> Cloud3D:
        raise RuntimeError("Yale B pseudo-3D is generated by MediaPipe FaceMesh during preprocessing")
